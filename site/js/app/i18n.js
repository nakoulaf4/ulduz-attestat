export function t(key, params = {}) {
  const lang = getLang();
  const table = DICT[lang] ?? DICT.ru;
  let str = table[key] ?? DICT.ru[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

export function getLocale() {
  return getLang() === 'az' ? 'az-AZ' : 'ru-RU';
}

export function subjectTitle(id) {
  const map = {
    math: 'subjectMath',
    ru: 'subjectRu',
    en: 'subjectEn',
    az: 'subjectAz',
  };
  return map[id] ? t(map[id]) : String(id || '').toUpperCase();
}

export function subjectShort(id) {
  const map = {
    math: 'subjectShortMath',
    ru: 'subjectShortRu',
    en: 'subjectShortEn',
    az: 'subjectShortAz',
  };
  return map[id] ? t(map[id]) : String(id || '').toUpperCase();
}

export function examDesc(subjectId, fallback = '') {
  const key = `examDesc_${subjectId}`;
  const lang = getLang();
  if (DICT[lang]?.[key]) return DICT[lang][key];
  return fallback || DICT.ru[key] || '';
}

export function formatPoints(pts) {
  const n = Number(pts ?? 1);
  if (getLang() === 'az') return `${n} bal`;
  if (n === 1) return '1 балл';
  if (n >= 2 && n <= 4) return `${n} балла`;
  return `${n} баллов`;
}

export function formatFormatBadge(format) {
  const map = {
    single: t('formatSingle'),
    multi: t('formatMulti'),
    short: t('formatShort'),
    match: t('formatMatch'),
    order: t('formatOrder'),
    open: t('formatOpen'),
  };
  return map[format] ?? format;
}

export function formatDifficulty(diff) {
  if (diff === 1) return { level: 1, label: t('difficulty1'), short: t('difficulty1') };
  if (diff === 3) return { level: 3, label: t('difficulty3'), short: t('difficulty3') };
  return { level: 2, label: t('difficulty2'), short: t('difficulty2') };
}

export function formatDateTime(ts) {
  if (!ts) return '—';
  try {
    return new Date(ts).toLocaleString(getLocale(), {
      day: '2-digit',
      month: '2-digit',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return String(ts);
  }
}
