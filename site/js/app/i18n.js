export function t(key, params = {}) {
  const lang = getLang();
  const table = DICT[lang] ?? DICT.ru;
  let str = table[key] ?? DICT.ru[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

export function getLocale() {
  return getLang() === 'az' ? 'az-AZ' : 'ru-RU';
}

export function subjectTitle(id) {
  const map = {
    math: 'subjectMath',
    ru: 'subjectRu',
    en: 'subjectEn',
    az: 'subjectAz',
    physics: 'subjectPhysics',
    chemistry: 'subjectChemistry',
    biology: 'subjectBiology',
    history: 'subjectHistory',
    geography: 'subjectGeography',
    informatics: 'subjectInformatics',
  };
  return map[id] ? t(map[id]) : String(id || '').toUpperCase();
}

